export const getRandomNameForNationality = (nationality: keyof typeof nameData): string => {
    const nameList = nameData[nationality];
    if (!nameList || nameList.length === 0) {
        // Fallback to a random list if the specific nationality isn't mapped
        const fallbackList = [
            ...britishNames, 
            ...americanNames, 
            ...canadianNames
        ];
        const { firstName, surname } = getRandomItem(fallbackList);
        return `${firstName} ${surname}`;
    }
    const { firstName, surname } = getRandomItem(nameList);
    return `${firstName} ${surname}`;
};