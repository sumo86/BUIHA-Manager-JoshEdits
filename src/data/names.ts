interface Name {
    firstName: string;
    surname: string;
}

const parseCsv = (csvString: string): Name[] => {
    const names: Name[] = [];
    if (!csvString) return names;
    const lines = csvString.trim().split('\n');
    // Skip header line by starting at 1
    for (let i = 1; i < lines.length; i++) {
        const [firstName, surname] = lines[i].split(',');
        if (firstName && surname) {
            names.push({ firstName: firstName.trim(), surname: surname.trim() });
        }
    }
    return names;
};

